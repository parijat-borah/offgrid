import type { Budget } from "./budget";
import type { Itinerary } from "./itinerary";
import { DIFFICULTY_LABELS, formatINR, formatNumber, HAZARD_LABELS, monthName } from "./labels";
import type { PackingGroup } from "./packing";
import type { Place, PlannerInput, Region } from "./schemas";
import type { SeasonCheck } from "./season";

export interface ExportInput {
  input: PlannerInput;
  place: Place;
  region: Region;
  season: SeasonCheck;
  itinerary: Itinerary;
  budget: Budget;
  packing: PackingGroup[];
  shareUrl?: string;
  generatedAt?: Date;
}

const RULE = "=".repeat(60);
const SUB = "-".repeat(60);

/** A plain-text plan that reads well on a phone, in WhatsApp, or printed. */
export function planToText(x: ExportInput): string {
  const { input, place, region, season, itinerary, budget, packing } = x;
  const out: string[] = [];
  const line = (s = "") => out.push(s);

  line(RULE);
  line(`OFFGRID TRIP PLAN: ${place.name.toUpperCase()}`);
  line(RULE);
  line(`${place.district}, ${region.name} · ${DIFFICULTY_LABELS[place.difficulty]} · up to ${formatNumber(place.max_altitude_m)} m`);
  line(`${itinerary.plannedDays} days in ${monthName(input.month)} · ${input.groupSize} ${input.groupSize === 1 ? "person" : "people"}`);
  line(place.summary);
  line();

  if (season.status !== "good") {
    line(`SEASON WARNING (${monthName(input.month)})`);
    season.reasons.forEach((r) => line(`  ! ${r}`));
    line();
  }

  line("ITINERARY");
  line(SUB);
  for (const d of itinerary.days) {
    const meta = [d.trek_km > 0 ? `${d.trek_km} km` : null, `sleep ${formatNumber(d.sleep_alt_m)} m`].filter(Boolean).join(" · ");
    line(`Day ${d.day}: ${d.title} (${meta})`);
    line(`  ${d.detail}`);
    d.warnings.forEach((w) => line(`  ! ${w}`));
  }
  itinerary.warnings.forEach((w) => line(`! ${w}`));
  line();

  line(`BUDGET PER PERSON (estimate, prices checked ${budget.lastVerified})`);
  line(SUB);
  for (const l of budget.lines) line(`${l.label.padEnd(36)} ${formatINR(l.perPerson).padStart(10)}`);
  line(`${`Buffer (${budget.bufferPct}%)`.padEnd(36)} ${formatINR(budget.bufferPerPerson).padStart(10)}`);
  line(`${"TOTAL per person".padEnd(36)} ${formatINR(budget.totalPerPerson).padStart(10)}`);
  if (budget.groupSize > 1) {
    line(`${`TOTAL for ${budget.groupSize} people`.padEnd(36)} ${formatINR(budget.totalGroup).padStart(10)}`);
  }
  line();

  line("PACKING LIST");
  line(SUB);
  for (const g of packing) {
    line(`${g.label}:`);
    g.items.forEach((i) => line(`  [ ] ${i.label}`));
  }
  line();

  line("SAFETY");
  line(SUB);
  if (place.hazards.length) line(`Hazards: ${place.hazards.map((h) => HAZARD_LABELS[h]).join(", ")}`);
  place.safety_notes.forEach((n) => line(`  - ${n}`));
  line(`Permits: ${place.permit_notes}`);
  line("Emergency numbers:");
  region.emergency.forEach((e) => line(`  ${e.number.padEnd(6)} ${e.label}`));
  line();

  line(SUB);
  line("All costs are estimates. Confirm road, weather and permit status locally before you go.");
  if (x.shareUrl) line(`Open this plan: ${x.shareUrl}`);
  line(`Generated by OFFGRID on ${(x.generatedAt ?? new Date()).toISOString().slice(0, 10)}`);
  return out.join("\n") + "\n";
}

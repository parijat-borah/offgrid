import { budgetBreakdown, plannedDays, PlannerInputSchema } from "@offgrid/core";
import { Router } from "express";
import { z } from "zod";
import type { Ctx } from "../../context";
import { badRequest, conflict, parse } from "../../lib/errors";
import { nowIso } from "../../lib/time";
import { requireAuth, userIdOf } from "../../middleware/auth";
import { limiter } from "../../middleware/rateLimit";
import { completeTrip, ownedTrip, tripDtos } from "./service";

const TripId = z.uuid("Trip ids are UUIDs generated by the client.");
const IsoDate = z.string().regex(/^\d{4}-\d{2}-\d{2}$/);

const UpsertSchema = z.object({
  placeId: z.string().max(64),
  plannerInput: PlannerInputSchema,
  startDate: IsoDate.nullable().optional(),
  notes: z.string().max(2000).optional(),
});

const PointsSchema = z.object({
  points: z
    .array(
      z.object({
        ts: z.number().int().positive(),
        lat: z.number().min(-90).max(90),
        lon: z.number().min(-180).max(180),
        alt: z.number().min(-500).max(9000).nullable().optional(),
        accuracy: z.number().min(0).max(10_000).nullable().optional(),
      }),
    )
    .min(1)
    .max(500),
  // "beacon" points only arrive through the signed relay (POST /beacons/relay), never from the phone.
  source: z.enum(["gps", "simulated"]).default("gps"),
});

const CompleteSchema = z.object({
  actualSpendPp: z.number().int().min(0).max(1_000_000).optional(),
  notes: z.string().max(2000).optional(),
});

const POINT_WINDOW_BEFORE_START_MS = 24 * 3_600_000;

export function tripRoutes(ctx: Ctx): Router {
  const r = Router();
  r.use(requireAuth(ctx));
  const writes = limiter(ctx, 30);

  r.get("/", async (req, res) => {
    const status = typeof req.query.status === "string" ? req.query.status : null;
    let q = ctx.db.selectFrom("trips").selectAll().where("owner_id", "=", userIdOf(res));
    if (status) q = q.where("status", "=", status);
    const rows = await q.orderBy("updated_at", "desc").limit(200).execute();
    res.json(await tripDtos(ctx.db, rows));
  });

  r.get("/:id", async (req, res) => {
    const [dto] = await tripDtos(ctx.db, [await ownedTrip(ctx.db, userIdOf(res), parse(TripId, req.params.id))]);
    res.json(dto);
  });

  // Idempotent upsert keyed by the client's UUID, so an offline save can be retried safely.
  r.put("/:id", writes, async (req, res) => {
    const id = parse(TripId, req.params.id);
    const body = parse(UpsertSchema, req.body);
    const place = ctx.content.place(body.placeId);
    if (!place) throw badRequest("Unknown place.", { placeId: "Unknown place" });
    // Recompute the budget server-side rather than trusting a client-supplied number.
    const budgetPp = budgetBreakdown(
      place,
      plannedDays(place, body.plannerInput.days),
      body.plannerInput.groupSize,
      ctx.content.planner.rules,
    ).totalPerPerson;

    const existing = await ctx.db.selectFrom("trips").select(["owner_id", "status"]).where("id", "=", id).executeTakeFirst();
    const now = nowIso();
    if (existing) {
      if (existing.owner_id !== userIdOf(res)) throw badRequest("Trip id already in use.");
      if (existing.status !== "planned") throw conflict("Only planned trips can be edited.");
      await ctx.db
        .updateTable("trips")
        .set({
          place_id: place.id,
          planner_input: JSON.stringify(body.plannerInput),
          budget_pp: budgetPp,
          start_date: body.startDate ?? null,
          ...(body.notes !== undefined ? { notes: body.notes } : {}),
          updated_at: now,
        })
        .where("id", "=", id)
        .execute();
    } else {
      await ctx.db
        .insertInto("trips")
        .values({
          id,
          owner_id: userIdOf(res),
          place_id: place.id,
          status: "planned",
          start_date: body.startDate ?? null,
          planner_input: JSON.stringify(body.plannerInput),
          budget_pp: budgetPp,
          actual_spend_pp: null,
          validation: null,
          validation_reasons: "[]",
          distance_km: null,
          elevation_gain_m: null,
          notes: body.notes ?? "",
          xp_awarded: 0,
          started_at: null,
          completed_at: null,
          created_at: now,
          updated_at: now,
        })
        .execute();
    }
    const [dto] = await tripDtos(ctx.db, [await ownedTrip(ctx.db, userIdOf(res), id)]);
    res.status(existing ? 200 : 201).json(dto);
  });

  r.post("/:id/start", writes, async (req, res) => {
    const trip = await ownedTrip(ctx.db, userIdOf(res), parse(TripId, req.params.id));
    if (trip.status !== "planned") throw conflict("Only a planned trip can be started.");
    const now = nowIso();
    await ctx.db.updateTable("trips").set({ status: "active", started_at: now, updated_at: now }).where("id", "=", trip.id).execute();
    const [dto] = await tripDtos(ctx.db, [await ownedTrip(ctx.db, userIdOf(res), trip.id)]);
    res.json(dto);
  });

  r.post("/:id/points", limiter(ctx, 120), async (req, res) => {
    const trip = await ownedTrip(ctx.db, userIdOf(res), parse(TripId, req.params.id));
    if (trip.status !== "active") throw conflict("GPS points can only be added while the trip is active.");
    const body = parse(PointsSchema, req.body);
    // The demo-only simulated track has no place in production, even though it never reaches the leaderboards.
    if (body.source === "simulated" && ctx.config.env === "production") throw badRequest("Simulated GPS is only available in demo mode.");
    // Points buffered offline may predate the server's start time a little; future ones never count.
    const earliest = Date.parse(trip.started_at!) - POINT_WINDOW_BEFORE_START_MS;
    const latest = Date.now() + ctx.content.game.xp.plausibility.future_tolerance_min * 60_000;
    const valid = body.points.filter((p) => p.ts >= earliest && p.ts <= latest);
    if (valid.length > 0) {
      await ctx.db
        .insertInto("trip_points")
        .values(valid.map((p) => ({ trip_id: trip.id, ts: p.ts, lat: p.lat, lon: p.lon, alt: p.alt ?? null, accuracy: p.accuracy ?? null, source: body.source })))
        .onConflict((oc) => oc.columns(["trip_id", "ts"]).doNothing())
        .execute();
    }
    res.json({ accepted: valid.length, rejected: body.points.length - valid.length });
  });

  r.post("/:id/complete", writes, async (req, res) => {
    const body = parse(CompleteSchema, req.body ?? {});
    res.json(await completeTrip(ctx, userIdOf(res), parse(TripId, req.params.id), body));
  });

  r.delete("/:id", writes, async (req, res) => {
    const trip = await ownedTrip(ctx.db, userIdOf(res), parse(TripId, req.params.id));
    if (trip.status === "completed") throw conflict("Completed trips stay in your history.");
    await ctx.db.updateTable("trips").set({ status: "cancelled", updated_at: nowIso() }).where("id", "=", trip.id).execute();
    res.status(204).end();
  });

  return r;
}
